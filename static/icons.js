function iconHTML(name, size) {
  const inner = ICONS[name];
  if (!inner) return '';
  const px = size || 18;
  return (
    '<svg class="i" viewBox="0 0 24 24" width="' + px + '" height="' + px +
    '" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" ' +
    'stroke-linejoin="round" aria-hidden="true">' + inner + '</svg>'
  );
}

function initIcons(root) {
  const r = root || document;
  const nodes = r.querySelectorAll ? r.querySelectorAll('[data-i]') : [];
  nodes.forEach((el) => {
    const name = el.getAttribute('data-i');
    const size = parseInt(el.getAttribute('data-s') || '18', 10);
    if (!name || !ICONS[name]) return;
    el.innerHTML = iconHTML(name, size);
    el.classList.add('i-host');
  });
}

